/**
 * Мобильные экраны, у которых в макете своя навигация: сверху навбар
 * «назад · заголовок · действие», снизу — своя кнопка (купить / оформить).
 * Общая шапка и нижняя таблетка на них не рендерятся: иначе получаются две
 * шапки сверху и две плашки внизу, перекрывающие CTA.
 *
 * Референсы: «Мобилка - 3 Купон», «- 4 Корзина», «- 5 Оплата», «- 6 Оплачено».
 */
const OWN_CHROME = [
  /^\/(ru|uz)\/coupons\/\d+/,
  /^\/(ru|uz)\/cart\/?$/,
  /^\/(ru|uz)\/checkout\/?$/,
  /^\/(ru|uz)\/payment\//,
];

export function hasOwnChrome(pathname: string): boolean {
  return OWN_CHROME.some((route) => route.test(pathname));
}

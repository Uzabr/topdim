/**
 * Кураторская подборка «ситуаций» для секции «Что хотите сегодня?».
 *
 * Источник: design_handoff_sizbiz → «Дизайн-документация», раздел
 * «10.6 Навигация» + макет «Главная - образец» (секция «Ситуации»).
 *
 * Ситуации — это НЕ категории. Категории остаются отдельным механизмом
 * (фильтр-табы ленты «Подобрали для вас»). Ситуация — навигация по жизненному
 * сценарию/интенту; в продуктовой механике это поисковый вход (Мобилка-9:
 * «без запроса — плитки ситуаций… клик → результаты поиска по названиям/тегам»).
 *
 * ВРЕМЕННАЯ РЕАЛИЗАЦИЯ. Список и `query` заданы здесь, во фронтенде, а счётчик
 * «N купонов» берётся из реального поиска каталога (`totalElements`) — фейковых
 * чисел нет, при нуле счётчик скрывается. Полноценная управляемая фича
 * (подборки с картинкой, точным счётчиком и кураторским набором купонов из БД)
 * реализуется на бэкенде — см. docs/backend-tasks/situations-podborki.md.
 * Когда появится API `GET /api/v1/situations`, этот файл заменяется вызовом API,
 * а разметка компонентов не меняется (они уже рендерят список ситуаций).
 */
export interface Situation {
  /** Стабильный ключ = i18n-ключ заголовка в `home.situations.<key>`. */
  key: string;
  /**
   * Поисковый запрос-заглушка: ведёт на `/search?q=` и питает счётчик купонов.
   * После появления backend-подборок заменяется реальной привязкой купонов.
   */
  query: string;
  /** Первая плитка — тёмный «ситуация-хиро», занимает две колонки. */
  featured?: boolean;
}


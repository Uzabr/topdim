-- 2) primary locations
INSERT INTO merchant_locations (merchant_id, title, address, phone, working_hours, is_primary, active)
SELECT m.id, 'Основной филиал', s.addr, s.phone, s.hours, TRUE, TRUE
FROM _seed s JOIN merchants m ON m.name = s.mname AND m.website = 'https://demo.sizbiz.uz';

-- 3) ACTIVE offers
INSERT INTO coupon_offers (title, offer_description, merchant_id, category_id, old_price, from_price, discount_percent, cover_image_url, buy_until, use_until, is_gift_available, status)
SELECT s.otitle, s.odesc, m.id,
       (SELECT id FROM categories WHERE slug = s.cat),
       s.oldp, s.fromp, s.disc,
       'https://images.unsplash.com/photo-'||s.cover||'?auto=format&fit=crop&w=1200&q=80',
       TIMESTAMP '2026-12-31 23:59:00', TIMESTAMP '2027-03-31 23:59:00', FALSE, 'ACTIVE'
FROM _seed s JOIN merchants m ON m.name = s.mname AND m.website = 'https://demo.sizbiz.uz';

-- 4) sold-out options 1/1
INSERT INTO coupon_options (coupon_offer_id, title, regular_price, coupon_price, quantity_limit, quantity_sold, status)

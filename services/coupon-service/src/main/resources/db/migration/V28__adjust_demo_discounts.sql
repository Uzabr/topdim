        ('СПА-день: хаммам + пилинг + массаж',  440000.00),
        ('Чистка лица + уходовая программа',    360000.00),
        ('Маникюр + педикюр комбо',             297500.00),
        ('Расслабляющий массаж 60 минут',       396000.00),
        ('Брови + ламинирование ресниц',        297600.00),
        ('Вечерний макияж + укладка',           475000.00),
        ('Восстановление волос + укладка',      257600.00),
        ('Косметология: пилинг + массаж лица',  540000.00)
)
UPDATE coupon_options o
SET coupon_price = d.newprice
FROM d, coupon_offers c, merchants m
WHERE o.coupon_offer_id = c.id
  AND c.merchant_id = m.id
  AND m.website = 'https://demo.sizbiz.uz'
  AND c.title = d.title;

-- V28: реалистичные (небольшие, разные) скидки для демо-салонов из V27.
--
-- V27 задавал 30–40% — слишком много для реальных салонов. Здесь ставим разные
-- значения 5–20% и пересчитываем from_price (обложка карточки) и coupon_options.coupon_price
-- (цена покупки) как old_price * (1 - discount/100). old_price/regular_price не трогаем.
-- Правится ТОЛЬКО демо (merchants.website='https://demo.sizbiz.uz'). V27 не редактируем
-- (её checksum уже зафиксирован Flyway) — вносим изменения отдельной миграцией.

-- Маппинг: title оффера → (новый % скидки, новая цена = old_price*(1-%/100))
WITH d(title, disc, newprice) AS (
    VALUES
        ('Маникюр + гель-лак',                 10, 225000.00),  -- old 250000
        ('Женская стрижка + окрашивание',      15, 510000.00),  -- old 600000
        ('СПА-день: хаммам + пилинг + массаж',  20, 440000.00),  -- old 550000
        ('Чистка лица + уходовая программа',    10, 360000.00),  -- old 400000
        ('Маникюр + педикюр комбо',             15, 297500.00),  -- old 350000
        ('Расслабляющий массаж 60 минут',       12, 396000.00),  -- old 450000
        ('Брови + ламинирование ресниц',         7, 297600.00),  -- old 320000
        ('Вечерний макияж + укладка',            5, 475000.00),  -- old 500000
        ('Восстановление волос + укладка',       8, 257600.00),  -- old 280000
        ('Косметология: пилинг + массаж лица',  10, 540000.00)   -- old 600000
)
UPDATE coupon_offers c
SET discount_percent = d.disc,
    from_price       = d.newprice
FROM d, merchants m
WHERE c.merchant_id = m.id
  AND m.website = 'https://demo.sizbiz.uz'
  AND c.title = d.title;


package uz.topdim.identity.entity;

/**
 * Уровень доверия аккаунта — ортогонален роли ({@link Role}).
 *
 * <ul>
 *   <li>{@code L0} — базовый: аккаунт создан «в один тап» (например, через Telegram).
 *       Может смотреть и покупать за деньги, но НЕ получает перки
 *       (промокоды, скидку первого заказа, бесплатные купоны).</li>
 *   <li>{@code L1} — верифицирован: подтверждён телефон (OTP) или совершена
 *       успешная оплата. Открывает перки.</li>
 * </ul>
 *
 * Модель прогрессивного доверия защищает от массовой регистрации фейками
 * (дешёвые Telegram-аккаунты дают L0 без экономической выгоды).
 */
public enum TrustLevel {
    L0,
    L1
}
